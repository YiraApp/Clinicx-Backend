import { PDFDocument } from "pdf-lib";
import { medicalDocumentRepository } from "../../repositories/Appointments/medical-document.repository.js";
import { blobService } from "../Common/blob.service.js";

/**
 * AI reading of medical documents (lab reports, scans, discharge summaries).
 * The model call runs here so the API key never ships inside the mobile app.
 */

export const MAX_REPORT_PAGES = 10;
const MAX_REPORT_BYTES = 15 * 1024 * 1024;
const GEMINI_URL = "https://generativelanguage.googleapis.com/v1beta/models";
const ANALYSIS_VERSION = 1;

export const REPORT_DISCLAIMER =
    "This summary was generated by AI to help you understand your report. It is not a diagnosis. " +
    "Always confirm results and treatment with a qualified doctor.";

export class ReportAnalysisError extends Error {
    constructor(message: string, public readonly code: string, public readonly httpStatus = 400) {
        super(message);
    }
}

export interface PreparedReport {
    buffer: Buffer;
    mimeType: string;
    fileName: string;
    pageCount: number;
}

type Flag = "normal" | "low" | "high" | "critical_low" | "critical_high" | "abnormal" | "unknown";
type OverallStatus = "normal" | "attention" | "critical" | "unknown";
type Urgency = "none" | "routine" | "soon" | "urgent" | "emergency";

const PROMPT = `You are a careful clinical report reader helping a patient in India understand their own medical document.
Read EVERY page of the attached document (up to ${MAX_REPORT_PAGES} pages) and return ONLY one JSON object with this shape:

{
  "isMedicalDocument": boolean,
  "documentType": "Lab Report" | "Imaging Report" | "Discharge Summary" | "Prescription" | "Consultation Note" | "Vaccination Record" | "Insurance" | "Other",
  "title": "short name of the report, e.g. Complete Blood Count, Lipid Profile, MRI Lumbar Spine",
  "reportDate": "YYYY-MM-DD or empty",
  "labName": "lab / hospital / diagnostic centre name or empty",
  "referringDoctor": "doctor name printed on the report or empty",
  "patientName": "as printed or empty",
  "patientAge": "as printed, e.g. 34 Y, or empty",
  "patientGender": "Male | Female | Other | empty",
  "readability": "good" | "partial" | "poor",
  "readabilityNote": "say which page or part was unclear, or empty",
  "overallStatus": "normal" | "attention" | "critical",
  "headline": "one plain-language sentence a patient understands, e.g. 'Most results are normal, but your blood sugar is high.'",
  "summary": "3-5 short sentences in plain language explaining what the report shows overall",
  "keyFindings": ["the most important observations, plain language, most important first, max 6"],
  "criticalAlerts": [
    { "title": "short", "detail": "what is dangerous and why, plain language", "action": "what the patient should do now" }
  ],
  "sections": [
    {
      "name": "panel or section name, e.g. Lipid Profile, Kidney Function, Findings",
      "tests": [
        {
          "name": "test name as a patient would recognise it (add the abbreviation in brackets, e.g. Haemoglobin (Hb))",
          "value": "result exactly as printed",
          "unit": "unit or empty",
          "referenceRange": "range printed on the report, or the standard adult range if none is printed",
          "flag": "normal" | "low" | "high" | "critical_low" | "critical_high" | "abnormal" | "unknown",
          "meaning": "one short plain-language sentence on what this result means for the patient"
        }
      ]
    }
  ],
  "impression": "for imaging / pathology: the radiologist's or pathologist's impression in plain language, else empty",
  "possibleConditions": [
    { "name": "condition the findings may point to", "likelihood": "possible" | "likely", "explanation": "why, in plain language" }
  ],
  "doctorConsultation": {
    "needed": boolean,
    "urgency": "none" | "routine" | "soon" | "urgent" | "emergency",
    "specialty": "the most suitable specialist, e.g. General Physician, Endocrinologist, Cardiologist, Nephrologist",
    "timeframe": "e.g. 'Today', 'Within 2-3 days', 'Within 2 weeks', 'At your next routine visit'",
    "reason": "why the patient should see this doctor, plain language"
  },
  "recommendations": [
    { "category": "diet" | "lifestyle" | "monitoring" | "followUpTest" | "medication" | "general", "text": "specific, practical advice" }
  ],
  "followUpTests": ["tests a doctor may order next, with when, e.g. 'HbA1c in 3 months'"],
  "questionsForDoctor": ["questions the patient can ask at the consultation, max 5"],
  "confidence": number 0-100
}

RULES
- Extract EVERY test result on EVERY page. Group them into sections the way the report does.
- Use the reference range printed on the report to set each flag. Use critical_low / critical_high only for values that are dangerously far out of range (panic values, e.g. potassium > 6.0, glucose < 54 or > 400 mg/dL, haemoglobin < 7 g/dL, platelets < 50,000).
- overallStatus: "critical" if any value or finding needs urgent care; "attention" if anything is out of range or abnormal; "normal" only if everything is within range.
- urgency: "emergency" = go to a hospital now; "urgent" = see a doctor within 24-48 hours; "soon" = within 1-2 weeks; "routine" = next regular visit; "none" = nothing needed.
- For imaging or text reports with no numeric tests, put the findings in a section named "Findings" with each finding as a test whose value is the finding text and flag normal/abnormal.
- If the document is not a medical document, set isMedicalDocument false, overallStatus "normal", and explain in summary.
- If it is a prescription, list the medicines as a section named "Medicines" (value = dose and frequency, flag "unknown").
- Never invent values that are not on the document. If something is unreadable, say so in readabilityNote and lower confidence.
- Do not prescribe medicines or doses. Recommendations must be safe, general and specific to these results.
- Write for a patient with no medical background: short sentences, no jargon without an explanation.
- Translate non-English text to English.
- Return ONLY valid JSON, no markdown.`;

class MedicalReportAiService {
    private get apiKey(): string {
        return (process.env.GEMINI_API_KEY || "").trim();
    }

    private get model(): string {
        return (process.env.GEMINI_MODEL || "gemini-2.5-flash").trim();
    }

    private get thinkingBudget(): number {
        const n = Number(process.env.GEMINI_THINKING_BUDGET);
        return Number.isFinite(n) && n >= 0 ? n : 0;
    }

    get isConfigured(): boolean {
        return this.apiKey.length > 0;
    }

    /**
     * Checks the uploaded files and turns them into one report: a PDF of up to
     * 10 pages, or 1-10 photos (several photos are joined into one PDF).
     */
    async prepareReport(files: Express.Multer.File[], title?: string): Promise<PreparedReport> {
        if (!files || files.length === 0) {
            throw new ReportAnalysisError("Add a PDF or at least one photo of your report.", "NO_FILES");
        }

        const baseName = this.safeName(title) || `Report_${new Date().toISOString().slice(0, 10)}`;
        const pdfs = files.filter((f) => this.isPdf(f));
        const images = files.filter((f) => this.isImage(f));

        if (pdfs.length + images.length !== files.length) {
            throw new ReportAnalysisError("Only PDF, JPG and PNG files are supported.", "UNSUPPORTED_TYPE");
        }
        if (pdfs.length > 0 && (pdfs.length > 1 || images.length > 0)) {
            throw new ReportAnalysisError("Upload one PDF, or photos of the pages, not both.", "MIXED_FILES");
        }

        if (pdfs.length === 1) {
            const file = pdfs[0];
            const pageCount = await this.countPdfPages(file.buffer);
            if (pageCount > MAX_REPORT_PAGES) {
                throw new ReportAnalysisError(
                    `This PDF has ${pageCount} pages. Reports can have up to ${MAX_REPORT_PAGES} pages.`,
                    "TOO_MANY_PAGES",
                );
            }
            return { buffer: file.buffer, mimeType: "application/pdf", fileName: `${baseName}.pdf`, pageCount };
        }

        if (images.length > MAX_REPORT_PAGES) {
            throw new ReportAnalysisError(
                `You added ${images.length} photos. Reports can have up to ${MAX_REPORT_PAGES} pages.`,
                "TOO_MANY_PAGES",
            );
        }

        if (images.length === 1) {
            const file = images[0];
            const ext = this.isPng(file) ? "png" : "jpg";
            return { buffer: file.buffer, mimeType: this.isPng(file) ? "image/png" : "image/jpeg", fileName: `${baseName}.${ext}`, pageCount: 1 };
        }

        const merged = await this.imagesToPdf(images);
        return { buffer: merged, mimeType: "application/pdf", fileName: `${baseName}.pdf`, pageCount: images.length };
    }

    /** Reads a report with the model and returns the cleaned-up analysis. */
    async analyzeBuffer(buffer: Buffer, mimeType: string, pageCount?: number): Promise<any> {
        if (!this.isConfigured) {
            throw new ReportAnalysisError("AI analysis is not set up on the server.", "NOT_CONFIGURED", 503);
        }
        if (buffer.length > MAX_REPORT_BYTES) {
            throw new ReportAnalysisError("This file is too large to analyse. Use a file under 15 MB.", "TOO_LARGE");
        }

        const controller = new AbortController();
        const timer = setTimeout(() => controller.abort(), 120_000);
        let response: Response;
        try {
            response = await fetch(`${GEMINI_URL}/${this.model}:generateContent`, {
                method: "POST",
                headers: { "Content-Type": "application/json", "x-goog-api-key": this.apiKey },
                signal: controller.signal,
                body: JSON.stringify({
                    contents: [
                        {
                            parts: [
                                { text: PROMPT },
                                { inlineData: { mimeType, data: buffer.toString("base64") } },
                            ],
                        },
                    ],
                    generationConfig: {
                        temperature: 0.1,
                        maxOutputTokens: 24576,
                        responseMimeType: "application/json",
                        // No extra reasoning: in testing it was faster (~12s vs ~90s) and flagged values more accurately.
                        thinkingConfig: { thinkingBudget: this.thinkingBudget },
                    },
                }),
            });
        } catch (err: any) {
            if (err?.name === "AbortError") {
                throw new ReportAnalysisError("The analysis took too long. Please try again.", "TIMEOUT", 504);
            }
            throw new ReportAnalysisError("Could not reach the AI service. Please try again.", "NETWORK", 502);
        } finally {
            clearTimeout(timer);
        }

        if (!response.ok) {
            const body = await response.text().catch(() => "");
            console.error(`[MedicalReportAI] Gemini ${response.status}: ${body.slice(0, 400)}`);
            if (response.status === 429) {
                throw new ReportAnalysisError("The AI service is busy. Please try again in a minute.", "RATE_LIMITED", 429);
            }
            if (response.status === 400) {
                throw new ReportAnalysisError("This file could not be read. Try a clearer photo or a different PDF.", "UNREADABLE");
            }
            throw new ReportAnalysisError("The AI service returned an error. Please try again.", "AI_ERROR", 502);
        }

        const data: any = await response.json();
        const candidate = data?.candidates?.[0];
        const text: string = (candidate?.content?.parts || [])
            .map((p: any) => p?.text || "")
            .join("")
            .trim();

        if (!text) {
            if (data?.promptFeedback?.blockReason) {
                throw new ReportAnalysisError("This file could not be analysed. Try a different file.", "BLOCKED");
            }
            throw new ReportAnalysisError("The AI returned no result. Please try again.", "EMPTY");
        }

        let parsed: any;
        try {
            parsed = JSON.parse(text.replace(/^```\w*\s*/, "").replace(/\s*```$/, ""));
        } catch {
            console.error("[MedicalReportAI] Could not parse model JSON:", text.slice(0, 300));
            throw new ReportAnalysisError("The report could not be understood. Try a clearer photo.", "PARSE");
        }

        return this.normalize(parsed, pageCount);
    }

    /** Analyses a stored document (cached unless [force]) and saves the result. */
    async analyzeDocument(documentId: number, requesterId: string | undefined, force = false): Promise<any> {
        const doc = await medicalDocumentRepository.findById(documentId);
        if (!doc) throw new ReportAnalysisError("Document not found.", "NOT_FOUND", 404);
        this.assertCanAnalyze(doc, requesterId);

        if (!force && doc.AiAnalysis) {
            const cached = this.parseStored(doc.AiAnalysis);
            if (cached) return cached;
        }
        if (!force && (doc.AiJobStatus === "processing" || doc.AiJobStatus === "fallback")) {
            throw new ReportAnalysisError(
                "Your report is still being analysed. We'll notify you when it's ready.",
                "ANALYSIS_PENDING",
                409,
            );
        }
        if (!doc.BlobUrl) {
            throw new ReportAnalysisError("The file for this document is not available.", "NO_FILE", 404);
        }

        const buffer = await blobService.downloadFile(doc.BlobUrl);
        // Older uploads often lack an extension or MIME type, so trust the bytes first.
        const mimeType = this.sniffMime(buffer) || this.mimeFor(doc.MimeType, doc.FileExtension, doc.FileName);
        if (!mimeType) {
            throw new ReportAnalysisError("Only PDF, JPG and PNG documents can be analysed.", "UNSUPPORTED_TYPE");
        }

        let pageCount = 1;
        if (mimeType === "application/pdf") {
            pageCount = await this.countPdfPages(buffer);
            if (pageCount > MAX_REPORT_PAGES) {
                throw new ReportAnalysisError(
                    `This PDF has ${pageCount} pages. AI analysis supports up to ${MAX_REPORT_PAGES} pages.`,
                    "TOO_MANY_PAGES",
                );
            }
        }

        const analysis = await this.analyzeBuffer(buffer, mimeType, pageCount);
        await this.saveAnalysis(documentId, analysis);
        return analysis;
    }

    /** The report as a PDF (a single photo becomes a one-page PDF). */
    async asPdf(prepared: PreparedReport): Promise<Buffer> {
        if (prepared.mimeType === "application/pdf") return prepared.buffer;
        return this.imagesToPdf([
            { buffer: prepared.buffer, mimetype: prepared.mimeType, originalname: prepared.fileName } as Express.Multer.File,
        ]);
    }

    async getStoredAnalysis(documentId: number): Promise<any | null> {
        const doc = await medicalDocumentRepository.findById(documentId);
        if (!doc) throw new ReportAnalysisError("Document not found.", "NOT_FOUND", 404);
        return doc.AiAnalysis ? this.parseStored(doc.AiAnalysis) : null;
    }

    async saveAnalysis(documentId: number, analysis: any): Promise<void> {
        await medicalDocumentRepository.saveAiAnalysis(documentId, JSON.stringify(analysis), analysis.overallStatus);
    }

    // ── Helpers ──────────────────────────────────────────────────────────

    private assertCanAnalyze(doc: any, requesterId?: string) {
        if (!requesterId) return;
        const id = requesterId.toLowerCase();
        const allowed = [doc.PatientId, doc.UploadedByUserId, doc.DoctorId]
            .filter(Boolean)
            .some((v: string) => String(v).toLowerCase() === id);
        if (!allowed) {
            throw new ReportAnalysisError("You can only analyse your own documents.", "FORBIDDEN", 403);
        }
    }

    private parseStored(raw: string): any | null {
        try {
            const parsed = JSON.parse(raw);
            return parsed && typeof parsed === "object" ? parsed : null;
        } catch {
            return null;
        }
    }

    /** Cleans up model output into the shape the app reads, whichever service produced it. */
    normalize(raw: any, pageCount?: number, model: string = this.model): any {
        const str = (v: any, max = 600) => (typeof v === "string" ? v.trim() : v == null ? "" : String(v).trim()).slice(0, max);
        const list = (v: any) => (Array.isArray(v) ? v : []);
        const strList = (v: any, max: number) => list(v).map((x: any) => str(x, 300)).filter(Boolean).slice(0, max);
        const oneOf = <T extends string>(v: any, allowed: readonly T[], fallback: T): T => {
            const s = str(v).toLowerCase();
            return (allowed.find((a) => a.toLowerCase() === s) ?? fallback) as T;
        };

        const flags = ["normal", "low", "high", "critical_low", "critical_high", "abnormal", "unknown"] as const;
        const sections = list(raw.sections)
            .map((s: any) => ({
                name: str(s?.name, 120) || "Results",
                tests: list(s?.tests)
                    .map((t: any) => ({
                        name: str(t?.name, 160),
                        value: str(t?.value, 300),
                        unit: str(t?.unit, 40),
                        referenceRange: str(t?.referenceRange, 120),
                        flag: oneOf<Flag>(t?.flag, flags, "unknown"),
                        meaning: str(t?.meaning, 300),
                    }))
                    .filter((t: any) => t.name || t.value),
            }))
            .filter((s: any) => s.tests.length > 0);

        const tests = sections.flatMap((s: any) => s.tests);
        const graded = tests.filter((t: any) => t.flag !== "unknown");
        const stats = {
            total: tests.length,
            normal: graded.filter((t: any) => t.flag === "normal").length,
            outOfRange: graded.filter((t: any) => ["low", "high", "abnormal"].includes(t.flag)).length,
            critical: graded.filter((t: any) => t.flag.startsWith("critical")).length,
        };

        const criticalAlerts = list(raw.criticalAlerts)
            .map((a: any) => ({ title: str(a?.title, 120), detail: str(a?.detail), action: str(a?.action) }))
            .filter((a: any) => a.title || a.detail)
            .slice(0, 6);

        const consult = raw.doctorConsultation || {};
        const urgency = oneOf<Urgency>(consult.urgency, ["none", "routine", "soon", "urgent", "emergency"], "routine");
        const isMedical = raw.isMedicalDocument !== false;

        // The model's verdict can only be raised by what it found, never lowered.
        let overallStatus = oneOf<OverallStatus>(raw.overallStatus, ["normal", "attention", "critical"], "attention");
        if (!isMedical) overallStatus = "unknown";
        else if (stats.critical > 0 || criticalAlerts.length > 0 || urgency === "emergency" || urgency === "urgent") overallStatus = "critical";
        else if (overallStatus === "normal" && stats.outOfRange > 0) overallStatus = "attention";

        const confidence = Math.max(0, Math.min(100, Math.round(Number(raw.confidence) || 0)));

        return {
            version: ANALYSIS_VERSION,
            isMedicalDocument: isMedical,
            documentType: str(raw.documentType, 60) || "Other",
            title: str(raw.title, 160),
            reportDate: str(raw.reportDate, 20),
            labName: str(raw.labName, 160),
            referringDoctor: str(raw.referringDoctor, 120),
            patientName: str(raw.patientName, 120),
            patientAge: str(raw.patientAge, 20),
            patientGender: str(raw.patientGender, 20),
            readability: oneOf(raw.readability, ["good", "partial", "poor"] as const, "good"),
            readabilityNote: str(raw.readabilityNote, 300),
            overallStatus,
            headline: str(raw.headline, 240),
            summary: str(raw.summary, 1200),
            keyFindings: strList(raw.keyFindings, 8),
            criticalAlerts,
            sections,
            stats,
            impression: str(raw.impression, 1200),
            possibleConditions: list(raw.possibleConditions)
                .map((c: any) => ({
                    name: str(c?.name, 120),
                    likelihood: oneOf(c?.likelihood, ["possible", "likely"] as const, "possible"),
                    explanation: str(c?.explanation, 400),
                }))
                .filter((c: any) => c.name)
                .slice(0, 5),
            doctorConsultation: {
                needed: isMedical && (consult.needed === true || overallStatus !== "normal"),
                urgency: overallStatus === "critical" && (urgency === "none" || urgency === "routine" || urgency === "soon") ? "urgent" : urgency,
                specialty: str(consult.specialty, 80) || "General Physician",
                timeframe: str(consult.timeframe, 80),
                reason: str(consult.reason, 500),
            },
            recommendations: list(raw.recommendations)
                .map((r: any) => ({
                    category: oneOf(r?.category, ["diet", "lifestyle", "monitoring", "followUpTest", "medication", "general"] as const, "general"),
                    text: str(r?.text, 400),
                }))
                .filter((r: any) => r.text)
                .slice(0, 10),
            followUpTests: strList(raw.followUpTests, 6),
            questionsForDoctor: strList(raw.questionsForDoctor, 6),
            confidence,
            pagesAnalyzed: pageCount ?? null,
            analyzedAt: new Date().toISOString(),
            model,
            disclaimer: REPORT_DISCLAIMER,
        };
    }

    private async countPdfPages(buffer: Buffer): Promise<number> {
        try {
            const pdf = await PDFDocument.load(buffer, { ignoreEncryption: true, updateMetadata: false });
            return pdf.getPageCount();
        } catch (err: any) {
            console.error("[MedicalReportAI] PDF could not be opened:", err?.message);
            throw new ReportAnalysisError("This PDF could not be opened. It may be damaged or password protected.", "BAD_PDF");
        }
    }

    /** Joins page photos into one PDF, each page sized to its photo. */
    private async imagesToPdf(images: Express.Multer.File[]): Promise<Buffer> {
        const pdf = await PDFDocument.create();
        for (const img of images) {
            let embedded;
            try {
                embedded = this.isPng(img) ? await pdf.embedPng(img.buffer) : await pdf.embedJpg(img.buffer);
            } catch {
                throw new ReportAnalysisError(`"${img.originalname}" could not be read. Use JPG or PNG photos.`, "BAD_IMAGE");
            }
            // Keep pages near A4 width so large camera photos don't make huge pages.
            const scale = Math.min(1, 1240 / embedded.width);
            const width = embedded.width * scale;
            const height = embedded.height * scale;
            const page = pdf.addPage([width, height]);
            page.drawImage(embedded, { x: 0, y: 0, width, height });
        }
        return Buffer.from(await pdf.save());
    }

    private isPdf(f: Express.Multer.File) {
        return f.mimetype === "application/pdf" || /\.pdf$/i.test(f.originalname);
    }

    private isPng(f: Express.Multer.File) {
        return f.mimetype === "image/png" || /\.png$/i.test(f.originalname);
    }

    private isImage(f: Express.Multer.File) {
        return this.isPng(f) || ["image/jpeg", "image/jpg", "image/pjpeg"].includes(f.mimetype) || /\.jpe?g$/i.test(f.originalname);
    }

    private sniffMime(buffer: Buffer): string | null {
        if (buffer.length < 4) return null;
        if (buffer.subarray(0, 4).toString("latin1") === "%PDF") return "application/pdf";
        if (buffer[0] === 0x89 && buffer[1] === 0x50 && buffer[2] === 0x4e && buffer[3] === 0x47) return "image/png";
        if (buffer[0] === 0xff && buffer[1] === 0xd8) return "image/jpeg";
        if (buffer.subarray(0, 4).toString("latin1") === "RIFF" && buffer.subarray(8, 12).toString("latin1") === "WEBP") return "image/webp";
        return null;
    }

    private mimeFor(mime?: string, ext?: string, name?: string): string | null {
        const probe = `${mime || ""} ${ext || ""} ${name || ""}`.toLowerCase();
        if (probe.includes("pdf")) return "application/pdf";
        if (probe.includes("png")) return "image/png";
        if (/jpe?g/.test(probe)) return "image/jpeg";
        if (probe.includes("webp")) return "image/webp";
        return null;
    }

    private safeName(title?: string): string {
        return (title || "")
            .trim()
            .replace(/\.[a-z0-9]{2,4}$/i, "")
            .replace(/[^\w\- ]+/g, "")
            .replace(/\s+/g, "_")
            .slice(0, 80);
    }
}

export const medicalReportAiService = new MedicalReportAiService();
